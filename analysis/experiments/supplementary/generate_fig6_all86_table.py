#!/usr/bin/env python3
"""Generate the complete Figure 6 all-86 supplementary performance table.

Point estimates are anchored to the retained Figure 6 ledger. Confidence
intervals come from the method-matched shared patient-cluster bootstrap
generated by ``bootstrap_fig6_all86_patient_clusters.py``.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path
from typing import Any


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DEFAULT_LEDGER = (
    ROOT
    / "experiments"
    / "exp4_confounder_audit"
    / "results"
    / "fig6_matched_86_top20_ledger.json"
)
DEFAULT_BOOTSTRAP_DIR = HERE / "outputs" / "fig6_all86_patient_bootstrap"
DEFAULT_BOOTSTRAP_SUMMARY = (
    DEFAULT_BOOTSTRAP_DIR / "fig6_all86_patient_cluster_bootstrap_tidy.csv"
)
DEFAULT_BOOTSTRAP_STATUS = (
    DEFAULT_BOOTSTRAP_DIR / "fig6_all86_patient_cluster_bootstrap_status.json"
)
DEFAULT_OUTPUT_DIR = HERE / "outputs" / "fig6_all86"
DEFAULT_REFERENCE_ORDER = HERE / "outputs" / "linear_probe_221_auc_ci.csv"

EXPECTED_N = 86
EXPECTED_HIGHER = 55
EXPECTED_LOWER = 31
EXPECTED_FULL_MEAN = 0.7405666115048649
# Corrected after the procedural-exclusion fix; full-bank mean is unaffected.
EXPECTED_RESTRICTED_MEAN = 0.7509881074874611
EXPECTED_N_BOOTSTRAP = 1_000
EXPECTED_N_PATIENTS = 2_223
EXPECTED_N_SCANS = 2_612
TOL = 1e-12
DISPLAY_NAME_OVERRIDES = {
    "505": "Other pulmonary inflammation or edema",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ledger", type=Path, default=DEFAULT_LEDGER)
    parser.add_argument(
        "--bootstrap-summary",
        type=Path,
        default=DEFAULT_BOOTSTRAP_SUMMARY,
    )
    parser.add_argument(
        "--bootstrap-status",
        type=Path,
        default=DEFAULT_BOOTSTRAP_STATUS,
    )
    parser.add_argument(
        "--reference-order",
        type=Path,
        default=DEFAULT_REFERENCE_ORDER,
        help="Complete 221-phenotype source used only to match Table S10 order.",
    )
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    return parser.parse_args()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def relative_to_root(path: Path) -> str:
    resolved = path.resolve()
    try:
        return str(resolved.relative_to(ROOT.resolve()))
    except ValueError:
        return str(resolved)


def latex_escape(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in value)


def display_phenotype(row: dict[str, Any]) -> str:
    phecode = str(row["phecode"])
    return DISPLAY_NAME_OVERRIDES.get(phecode, str(row["phenotype"]))


def load_bootstrap_rows(path: Path) -> dict[str, dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if len(rows) != EXPECTED_N:
        raise ValueError(f"expected {EXPECTED_N} bootstrap rows, found {len(rows)}")
    by_phecode = {str(row["phecode"]): row for row in rows}
    if len(by_phecode) != len(rows):
        raise ValueError("bootstrap phecodes are not unique")
    return by_phecode


def merge_and_validate(
    ledger_rows: list[dict[str, Any]],
    bootstrap_rows: dict[str, dict[str, str]],
    bootstrap_status: dict[str, Any],
) -> tuple[list[dict[str, Any]], dict[str, float | int]]:
    if len(ledger_rows) != EXPECTED_N:
        raise ValueError(f"expected {EXPECTED_N} ledger rows, found {len(ledger_rows)}")
    merged: list[dict[str, Any]] = []
    for ledger_row in ledger_rows:
        phecode = str(ledger_row["phecode"])
        if phecode not in bootstrap_rows:
            raise ValueError(f"bootstrap summary is missing phecode {phecode}")
        bootstrap_row = bootstrap_rows[phecode]
        full = float(ledger_row["full_auc_mean"])
        restricted = float(ledger_row["refined_auc_point"])
        if (
            abs(
                full
                - float(bootstrap_row["full_bank_auc_mean_across_20_fits"])
            )
            > TOL
        ):
            raise ValueError(f"full-bank point mismatch for {phecode}")
        if (
            abs(restricted - float(bootstrap_row["rule_restricted_auc"]))
            > TOL
        ):
            raise ValueError(f"rule-restricted point mismatch for {phecode}")
        if int(bootstrap_row["n_rule_retained_observations"]) != int(
            ledger_row["n_refined_concepts"]
        ):
            raise ValueError(f"retained-observation count mismatch for {phecode}")
        expected_direction = "higher" if restricted > full else "lower"
        if bootstrap_row["direction"] != expected_direction:
            raise ValueError(f"direction mismatch for {phecode}")

        values = {
            "full_ci_low": float(bootstrap_row["full_bank_ci_low"]),
            "full_ci_high": float(bootstrap_row["full_bank_ci_high"]),
            "restricted_ci_low": float(
                bootstrap_row["rule_restricted_ci_low"]
            ),
            "restricted_ci_high": float(
                bootstrap_row["rule_restricted_ci_high"]
            ),
        }
        if not all(math.isfinite(value) for value in values.values()):
            raise ValueError(f"non-finite interval for {phecode}")
        if values["full_ci_low"] > values["full_ci_high"]:
            raise ValueError(f"reversed full-bank interval for {phecode}")
        if values["restricted_ci_low"] > values["restricted_ci_high"]:
            raise ValueError(f"reversed restricted interval for {phecode}")
        if int(bootstrap_row["full_bank_n_bootstrap_valid"]) != EXPECTED_N_BOOTSTRAP:
            raise ValueError(f"incomplete full-bank bootstrap for {phecode}")
        if (
            int(bootstrap_row["rule_restricted_n_bootstrap_valid"])
            != EXPECTED_N_BOOTSTRAP
        ):
            raise ValueError(f"incomplete restricted bootstrap for {phecode}")
        merged.append(
            {
                **ledger_row,
                **values,
                "n_test_patients": int(bootstrap_row["n_test_patients"]),
                "n_test_scans": int(bootstrap_row["n_test_scans"]),
                "n_positive_test_scans": int(
                    bootstrap_row["n_positive_test_scans"]
                ),
                "direction": expected_direction,
            }
        )

    phecodes = [str(row["phecode"]) for row in merged]
    phenotypes = [str(row["phenotype"]) for row in merged]
    if len(set(phecodes)) != len(phecodes):
        raise ValueError("ledger phecodes are not unique")
    if len(set(phenotypes)) != len(phenotypes):
        raise ValueError("ledger phenotype names are not unique")
    if {row["n_test_patients"] for row in merged} != {EXPECTED_N_PATIENTS}:
        raise ValueError("unexpected test-patient count")
    if {row["n_test_scans"] for row in merged} != {EXPECTED_N_SCANS}:
        raise ValueError("unexpected test-scan count")

    full_mean = sum(float(row["full_auc_mean"]) for row in merged) / len(merged)
    restricted_mean = (
        sum(float(row["refined_auc_point"]) for row in merged) / len(merged)
    )
    higher = sum(row["direction"] == "higher" for row in merged)
    lower = sum(row["direction"] == "lower" for row in merged)
    if (higher, lower) != (EXPECTED_HIGHER, EXPECTED_LOWER):
        raise ValueError(f"direction counts changed: higher={higher}, lower={lower}")
    if abs(full_mean - EXPECTED_FULL_MEAN) > TOL:
        raise ValueError(f"full-bank mean changed: {full_mean}")
    if abs(restricted_mean - EXPECTED_RESTRICTED_MEAN) > TOL:
        raise ValueError(f"rule-restricted mean changed: {restricted_mean}")

    status_summary = bootstrap_status["summary"]
    if abs(float(status_summary["full_bank_mean_auc"]) - full_mean) > TOL:
        raise ValueError("bootstrap status full-bank mean does not match")
    if (
        abs(float(status_summary["rule_restricted_mean_auc"]) - restricted_mean)
        > TOL
    ):
        raise ValueError("bootstrap status rule-restricted mean does not match")
    summary = {
        "n_phenotypes": len(merged),
        "n_test_patients": EXPECTED_N_PATIENTS,
        "n_test_scans": EXPECTED_N_SCANS,
        "n_bootstrap": EXPECTED_N_BOOTSTRAP,
        "full_bank_mean_auc": full_mean,
        "full_bank_macro_ci_low": float(
            status_summary["full_bank_macro_ci_low"]
        ),
        "full_bank_macro_ci_high": float(
            status_summary["full_bank_macro_ci_high"]
        ),
        "rule_restricted_mean_auc": restricted_mean,
        "rule_restricted_macro_ci_low": float(
            status_summary["rule_restricted_macro_ci_low"]
        ),
        "rule_restricted_macro_ci_high": float(
            status_summary["rule_restricted_macro_ci_high"]
        ),
        "n_higher_rule_restricted": higher,
        "n_lower_rule_restricted": lower,
        "n_unchanged": 0,
    }
    return merged, summary


def order_like_table_s10(
    rows: list[dict[str, Any]],
    reference_path: Path,
) -> tuple[list[dict[str, Any]], dict[str, str]]:
    with reference_path.open(newline="", encoding="utf-8") as handle:
        reference_rows = list(csv.DictReader(handle))
    order: dict[str, int] = {}
    sectors: dict[str, str] = {}
    for index, row in enumerate(reference_rows):
        phecode = str(row["phecode"]).strip()
        if phecode in order:
            raise ValueError(f"duplicate reference phecode: {phecode}")
        order[phecode] = index
        sectors[phecode] = str(row["sector"]).strip()
    missing = [str(row["phecode"]) for row in rows if str(row["phecode"]) not in order]
    if missing:
        raise ValueError(f"eligible phecodes missing from Table S10 order: {missing}")
    return sorted(rows, key=lambda row: order[str(row["phecode"])]), sectors


def write_tidy_csv(
    path: Path,
    rows: list[dict[str, Any]],
    sectors: dict[str, str],
) -> None:
    fieldnames = [
        "sector",
        "phecode",
        "phenotype",
        "source_phenotype",
        "n_rule_retained_observations",
        "n_test_patients",
        "n_test_scans",
        "n_positive_test_scans",
        "full_bank_auc_mean_across_20_fits",
        "full_bank_ci_low",
        "full_bank_ci_high",
        "rule_restricted_auc",
        "rule_restricted_ci_low",
        "rule_restricted_ci_high",
        "direction",
    ]
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow(
                {
                    "sector": sectors[str(row["phecode"])],
                    "phecode": str(row["phecode"]),
                    "phenotype": display_phenotype(row),
                    "source_phenotype": str(row["phenotype"]),
                    "n_rule_retained_observations": int(
                        row["n_refined_concepts"]
                    ),
                    "n_test_patients": int(row["n_test_patients"]),
                    "n_test_scans": int(row["n_test_scans"]),
                    "n_positive_test_scans": int(row["n_positive_test_scans"]),
                    "full_bank_auc_mean_across_20_fits": (
                        f"{float(row['full_auc_mean']):.15g}"
                    ),
                    "full_bank_ci_low": f"{float(row['full_ci_low']):.15g}",
                    "full_bank_ci_high": f"{float(row['full_ci_high']):.15g}",
                    "rule_restricted_auc": (
                        f"{float(row['refined_auc_point']):.15g}"
                    ),
                    "rule_restricted_ci_low": (
                        f"{float(row['restricted_ci_low']):.15g}"
                    ),
                    "rule_restricted_ci_high": (
                        f"{float(row['restricted_ci_high']):.15g}"
                    ),
                    "direction": row["direction"],
                }
            )


def auc_ci_cell(
    value: float,
    low: float,
    high: float,
    bold: bool,
) -> str:
    content = rf"\mbox{{{value:.3f} ({low:.3f}, {high:.3f})}}"
    return rf"\textbf{{{content}}}" if bold else content


def table_header() -> str:
    return (
        "\\textbf{Phecode} & \\hspace*{0.5em}\\textbf{Phenotype} & "
        "\\textbf{$n_{\\mathrm{obs}}$} & "
        "\\makecell{\\textbf{Full-bank}\\\\\\textbf{AUROC}\\\\\\textbf{(95\\% CI)}} & "
        "\\makecell{\\textbf{Rule-restricted}\\\\\\textbf{AUROC}\\\\\\textbf{(95\\% CI)}} \\\\"
    )


def write_longtable(
    path: Path,
    rows: list[dict[str, Any]],
    summary: dict[str, float | int],
) -> None:
    lines = [
        "% Generated by experiments/supplementary/generate_fig6_all86_table.py.",
        "% Portrait-only; requires: \\usepackage{array,booktabs,longtable}.",
        "",
        "\\begingroup",
        "\\normalsize",
        "\\setlength{\\tabcolsep}{2pt}",
        "\\renewcommand{\\arraystretch}{1.0}",
        "\\setlength{\\LTcapwidth}{\\linewidth}",
        "\\setlength{\\LTleft}{0pt}",
        "\\setlength{\\LTright}{0pt plus 1fill}",
        (
            "\\begin{longtable}{@{}"
            ">{\\centering\\arraybackslash}p{0.095\\linewidth}"
            ">{\\raggedright\\arraybackslash}p{0.355\\linewidth}"
            ">{\\centering\\arraybackslash}p{0.075\\linewidth}"
            ">{\\centering\\arraybackslash}p{0.220\\linewidth}"
            ">{\\centering\\arraybackslash}p{0.220\\linewidth}@{}}"
        ),
        (
            "\\caption{\\textbf{Complete full-bank and rule-restricted ACT "
            "performance across all 86 restriction-eligible INSPECT phenotypes.} "
            "Values are held-out test AUROCs with two-sided 95\\% percentile "
            "CIs from 1,000 shared patient-cluster bootstrap "
            "resamples of 2,612 scans from 2,223 patients. All scans from each "
            "sampled patient received the same multiplicity. Within each "
            "resample, AUROC was recomputed for the fixed full-bank and "
            "rule-restricted probes and summarized as one value per column. "
            "Models were not refit "
            "within resamples, so intervals quantify held-out patient-sampling "
            "rather than model-fitting variability. $n_{\\mathrm{obs}}$ is the "
            "number of observations retained by the phenotype-specific rule "
            "set. Bold indicates the larger unrounded point estimate. Across "
            "all rows, mean AUROC was 0.741 for the full-bank reference and "
            "0.751 for the rule-restricted probes, and rule-restricted values were "
            "higher for 55 phenotypes and lower for 31. No per-phenotype or "
            "aggregate hypothesis tests were conducted, and comparisons are "
            "descriptive.}"
            "\\label{tab:supp-restriction-all86}\\\\"
        ),
        "\\toprule",
        table_header(),
        "\\midrule",
        "\\endfirsthead",
        "\\multicolumn{5}{c}{\\tablename\\ \\thetable\\ -- continued}\\\\",
        "\\toprule",
        table_header(),
        "\\midrule",
        "\\endhead",
        "\\midrule",
        "\\multicolumn{5}{r}{Continued on next page}\\\\",
        "\\endfoot",
        "\\bottomrule",
        "\\endlastfoot",
    ]

    for row in rows:
        full = float(row["full_auc_mean"])
        restricted = float(row["refined_auc_point"])
        full_cell = auc_ci_cell(
            full,
            float(row["full_ci_low"]),
            float(row["full_ci_high"]),
            full > restricted,
        )
        restricted_cell = auc_ci_cell(
            restricted,
            float(row["restricted_ci_low"]),
            float(row["restricted_ci_high"]),
            restricted > full,
        )
        n_observations = f"{int(row['n_refined_concepts']):,}"
        lines.append(
            f"{latex_escape(str(row['phecode']))} & "
            f"\\hspace*{{0.5em}}{latex_escape(display_phenotype(row))} & "
            f"\\mbox{{{n_observations}}} & "
            f"{full_cell} & {restricted_cell} \\\\"
        )

    full_mean = float(summary["full_bank_mean_auc"])
    restricted_mean = float(summary["rule_restricted_mean_auc"])
    lines.extend(
        [
            "\\midrule",
            "\\multicolumn{2}{l}{\\textbf{Mean across 86 phenotypes}} & "
            "\\mbox{--} & "
            f"{auc_ci_cell(full_mean, float(summary['full_bank_macro_ci_low']), float(summary['full_bank_macro_ci_high']), full_mean > restricted_mean)} & "
            f"{auc_ci_cell(restricted_mean, float(summary['rule_restricted_macro_ci_low']), float(summary['rule_restricted_macro_ci_high']), restricted_mean > full_mean)} \\\\",
            "\\end{longtable}",
            "\\endgroup",
            "",
        ]
    )
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    args = parse_args()
    ledger_path = args.ledger.resolve()
    bootstrap_summary_path = args.bootstrap_summary.resolve()
    bootstrap_status_path = args.bootstrap_status.resolve()
    reference_order_path = args.reference_order.resolve()
    output_dir = args.output_dir.resolve()
    for path in (
        ledger_path,
        bootstrap_summary_path,
        bootstrap_status_path,
        reference_order_path,
    ):
        if not path.exists():
            raise FileNotFoundError(path)
    output_dir.mkdir(parents=True, exist_ok=True)

    ledger = json.loads(ledger_path.read_text(encoding="utf-8"))
    bootstrap_status = json.loads(
        bootstrap_status_path.read_text(encoding="utf-8")
    )
    if bootstrap_status.get("status") != "complete":
        raise ValueError("patient-cluster bootstrap status is not complete")
    if bootstrap_status["method"]["n_resamples"] != EXPECTED_N_BOOTSTRAP:
        raise ValueError("patient-cluster bootstrap does not have 1,000 resamples")
    if not bootstrap_status["method"][
        "shared_patient_resamples_across_both_profiles_and_all_phenotypes"
    ]:
        raise ValueError("bootstrap resamples were not shared")
    bootstrap_rows = load_bootstrap_rows(bootstrap_summary_path)
    merged, summary = merge_and_validate(
        list(ledger["rows"]),
        bootstrap_rows,
        bootstrap_status,
    )
    rows, sectors = order_like_table_s10(merged, reference_order_path)

    csv_path = output_dir / "fig6_all86_performance_tidy.csv"
    tex_path = output_dir / "fig6_all86_performance_longtable.tex"
    status_path = output_dir / "fig6_all86_performance_status.json"
    write_tidy_csv(csv_path, rows, sectors)
    write_longtable(tex_path, rows, summary)
    status = {
        "schema_version": "fig6-all86-supplementary-table-v2",
        "status": "complete",
        "inputs": {
            "figure6_ledger": {
                "path": relative_to_root(ledger_path),
                "sha256": sha256(ledger_path),
            },
            "patient_cluster_bootstrap_summary": {
                "path": relative_to_root(bootstrap_summary_path),
                "sha256": sha256(bootstrap_summary_path),
            },
            "patient_cluster_bootstrap_status": {
                "path": relative_to_root(bootstrap_status_path),
                "sha256": sha256(bootstrap_status_path),
            },
            "table_s10_order": {
                "path": relative_to_root(reference_order_path),
                "sha256": sha256(reference_order_path),
                "used_for_values": False,
            },
        },
        "outputs": {
            "tidy_csv": {
                "path": relative_to_root(csv_path),
                "sha256": sha256(csv_path),
            },
            "latex_longtable": {
                "path": relative_to_root(tex_path),
                "sha256": sha256(tex_path),
            },
        },
        "summary": summary,
        "validation": {
            "all_86_rows_present": True,
            "all_intervals_use_1000_shared_patient_cluster_resamples": True,
            "delta_column_omitted": True,
            "direction_counts_match_main_text": True,
            "aggregate_means_match_main_text": True,
            "row_order_matches_table_s10": True,
            "display_only_name_overrides": DISPLAY_NAME_OVERRIDES,
        },
    }
    status_path.write_text(
        json.dumps(status, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(
        "Figure 6 all-86 table with matched patient-cluster CIs: "
        f"n={summary['n_phenotypes']}, "
        f"full={summary['full_bank_mean_auc']:.6f} "
        f"({summary['full_bank_macro_ci_low']:.6f}, "
        f"{summary['full_bank_macro_ci_high']:.6f}), "
        f"restricted={summary['rule_restricted_mean_auc']:.6f} "
        f"({summary['rule_restricted_macro_ci_low']:.6f}, "
        f"{summary['rule_restricted_macro_ci_high']:.6f})"
    )
    print(f"  -> {csv_path}")
    print(f"  -> {tex_path}")
    print(f"  -> {status_path}")


if __name__ == "__main__":
    main()
