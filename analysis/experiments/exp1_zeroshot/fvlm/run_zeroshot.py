def build_fvlm():
    """blip_pretrain.from_config with the authors' machine-specific bits neutralized
    (MAE init no-op'd, BERT built from a CXR-BERT-derived med_config, no pretrained DL).
    Our checkpoint then supplies all weights."""
    cfg = OmegaConf.load(REPO / "lavis/projects/blip/train/pretrain_ct.yaml").model
    cfg.load_pretrained = False; cfg.load_finetuned = False
    bert = glob.glob("/path/to/.cache/huggingface/hub/models--microsoft--"
                     "BiomedVLP-CXR-BERT-specialized/snapshots/*/config.json")[0]
    mc = json.load(open(bert))
    mc.update({"add_type_embeddings": False, "add_cross_attention": False, "encoder_width": 768})
    # PID-suffixed: build_fvlm() is called from many concurrent sharded processes
    # (extract_feats.py --shard i); a shared filename here is a write/read race
    # (one process's json.dump truncating the file while another mid-reads it ->
    # JSONDecodeError('Expecting value: line 1 column 1 (char 0)'), seen 2026-07-02
    # when 24-way sharding first exercised this path concurrently).
    medcfg = REPO / f"med_config_fvlm.{os.getpid()}.json"; json.dump(mc, open(medcfg, "w"))
    cfg.med_config_path = str(medcfg)

    # text encoder: skip pretrained DL (our ckpt has text_encoder.*); fix a cls-ordering bug.
    _xbert = XBertEncoder.from_config.__func__
    XBertEncoder.from_config = classmethod(
        lambda c_, cf_, from_pretrained=False: _xbert(c_, cf_, from_pretrained=False))
    XBertEncoder.get_output_embeddings = lambda self: (
        self.cls.predictions.decoder if hasattr(self, "cls") else None)
    # no-op the hardcoded MAE ViT init path (overwritten by our checkpoint anyway)
    _load = torch.load
    def _patched(p, *a, **k):
        if isinstance(p, str) and "mae_pretrain_vit_base" in p:
            return {"model": {}}
        return _load(p, *a, **k)
    torch.load = _patched
    model = registry.get_model_class(cfg.arch).from_config(cfg)
    torch.load = _load
    medcfg.unlink(missing_ok=True)

    sd = torch.load(str(WEIGHTS), map_location="cpu", weights_only=False)["model"]
    missing, unexpected = model.load_state_dict(sd, strict=False)
    unexpected = [k for k in unexpected if "queue" not in k]
    missing = [k for k in missing if "queue" not in k and "cls.predictions" not in k]
    assert not unexpected and not missing, f"load issue: missing={missing[:5]} unexpected={unexpected[:5]}"
    print(f"[fvlm load] OK (organs={model.organs}, query_tokens={tuple(model.query_tokens.shape)})")
    return model.to(DEVICE).eval()


# resize.py + preprocess.py, on-the-fly (image trilinear / mask nearest -> ~1,1,3mm ->
# transpose -> intensity [-1150,350]->[0,1]).
_LOAD = MT.LoadImaged(keys=["image", "label"], image_only=False, ensure_channel_first=True)
_TRANSPOSE = MT.Transposed(keys=["image", "label"], indices=(0, 3, 2, 1))
_INTENSITY = MT.ScaleIntensityRanged(keys=["image"], a_min=-1150, a_max=350,
                                     b_min=0.0, b_max=1.0, clip=True)


def preprocess(nii_path: str, mask_path: str):
    d = _LOAD({"image": nii_path, "label": mask_path})
    aff = d["image_meta_dict"]["affine"]
    spacing = (abs(aff[0, 0].item()), abs(aff[1, 1].item()), abs(aff[2, 2].item()))
    _, h, w, dd = d["image"].shape
    scale = [spacing[i] / r for i, r in enumerate((1.0, 1.0, 3.0))]
    target = [int(h * scale[1]), int(w * scale[0]), int(dd * scale[2])]
    d["image"] = MT.Resize(spatial_size=target, mode="trilinear")(d["image"])
    d["label"] = MT.Resize(spatial_size=target, mode="nearest")(d["label"])
    d = _TRANSPOSE(d)
    d = _INTENSITY(d)
    return d["image"].as_tensor().float(), d["label"].as_tensor().float()


def masks_to_boxes_3d(masks):
    d, h, w = masks.shape[-3:]
    dev = masks.device
    z, y, x = torch.meshgrid(torch.arange(d, device=dev).float(),
                             torch.arange(h, device=dev).float(),
                             torch.arange(w, device=dev).float(), indexing="ij")
    out = []
    for g in (x, y, z):
        gm = masks * g.unsqueeze(0)
        mx = gm.flatten(1).max(-1).values
        mn = gm.masked_fill(~masks.bool(), float("inf")).flatten(1).min(-1).values
        out += [mn, mx]
    xmn, xmx, ymn, ymx, zmn, zmx = out
    return torch.stack([xmn, ymn, zmn, xmx, ymx, zmx], 1)


def center_crop(image, mask, crop_size):
    x0, y0, z0, x1, y1, z1 = masks_to_boxes_3d(mask)[0].long()
    cd, ch, cw = max(crop_size[0], z1 - z0), max(crop_size[1], y1 - y0), max(crop_size[2], x1 - x0)
    cx, cy, cz = (x0 + x1) // 2, (y0 + y1) // 2, (z0 + z1) // 2
    d, h, w = image.shape[-3:]
    xs = max(0, cx - cw // 2); xe = min(w, xs + cw); xs = max(0, xe - cw)
    ys = max(0, cy - ch // 2); ye = min(h, ys + ch); ys = max(0, ye - ch)
    zs = max(0, cz - cd // 2); ze = min(d, zs + cd); zs = max(0, ze - cd)
    return (image[..., zs:ze, ys:ye, xs:xe], mask[..., zs:ze, ys:ye, xs:xe])


_PAD = MT.DivisiblePadd(keys=["image", "label"], k=(16, 16, 32), mode="constant",
                        constant_values=0, method="end")


@torch.no_grad()
def run_dataset(model, name, limit, summary, nshards=1, shard=-1):
    df, h5_idx, y, labels, prompts = C.load_dataset(name)          # labels == LABELS_18
    id_col = "NoteAcc_DEID" if name == "radchest" else "VolumeName"
    vols = df[id_col].astype(str).tolist()
    # mask dir mirrors gen_masks.py: ctrate->masks/, everything else->masks_<name>/
    masks_dir = HERE / (("masks" if name == "ctrate_test" else f"masks_{name}") + MASKS_SUFFIX)
    n = len(vols) if not limit else min(limit, len(vols))
    if shard >= 0:                                                 # encode one contiguous block
        per = math.ceil(n / max(1, nshards))
        lo, hi = shard * per, min((shard + 1) * per, n)
    else:
        lo, hi = 0, n
    _, items = NV.native_index(name)                              # raw scan items (nii/.npz)
    text_feat = model.prepare_text_feat(TEST_ITEMS)
    text_feat = {k: v.to(DEVICE) for k, v in text_feat.items()}   # ensure on cuda
    print(f"[devices] model={next(model.parameters()).device} "
          f"text_feat={next(iter(text_feat.values())).device}", flush=True)
    item_idx = {it: labels.index(it[1]) for it in TEST_ITEMS}     # map to LABELS_18 col
    covered = sorted(set(item_idx.values()))
    probs = np.full((n, len(labels)), np.nan, dtype=np.float64)
    t0 = time.time(); done = 0
    for i in range(lo, hi):
        fname = vols[i] if vols[i].endswith(".nii.gz") else vols[i] + ".nii.gz"
        mpath = masks_dir / fname
        if not mpath.exists():
            continue
        tmp = None
        try:
            if items[i]["kind"] == "nii":
                img_path = items[i]["path"]
            else:                                                  # .npz -> temp NIfTI
                hu, aff = NV.load_hu_affine(items[i])
                fd, tmp = tempfile.mkstemp(suffix=".nii.gz"); os.close(fd)
                nib.save(nib.Nifti1Image(hu, aff), tmp); img_path = tmp
            image, mask = preprocess(img_path, str(mpath))
            image = image[None].to(DEVICE); mask = mask[None].to(DEVICE)   # (1,1,D,H,W)
            present = [o for o in ORGANS if torch.eq(mask, ORGANS.index(o) + 1).any()]
            whole = {o: torch.eq(mask, ORGANS.index(o) + 1).sum().item() for o in present}
            test_items = [it for it in TEST_ITEMS if it[0] in present]
            organ_logits = {it: [] for it in test_items}
            for it in list(organ_logits.keys()):
                if organ_logits[it]:
                    continue
                oid = ORGANS.index(it[0])
                wp, wm = center_crop(image, torch.eq(mask, oid + 1), ROI)
                wm = wm.float(); wm[wm == 1] = oid + 1
                pad = _PAD({"image": wp[0], "label": wm[0]})
                organ_logits = model.forward_test_win(
                    pad["image"][None], pad["label"][None], organ_logits, present,
                    text_feat, {}, whole, skip_organ=oid)
            for it, pr in organ_logits.items():
                if pr:
                    probs[i, item_idx[it]] = float(np.concatenate(pr).mean(0)[1])
            done += 1
            if done % 50 == 0:
                print(f"  {i+1}/{n} (done={done}, {(time.time()-t0)/done:.1f}s/vol)", flush=True)
        except Exception as e:
            print(f"  [FAIL {i+1}/{n}] {vols[i]}: {repr(e)[:120]}", flush=True)
        finally:
            if tmp:
                os.remove(tmp)
    if shard >= 0:                          # SHARD: cache this block's rows, no scoring
        RESULTS.mkdir(parents=True, exist_ok=True)
        cache = RESULTS / f"{name}__shard{shard}of{nshards}__probsblock.npy"
        np.save(cache, probs[lo:hi])
        print(f"[shard {shard}/{nshards}] {name} rows [{lo},{hi}) ({hi-lo}) -> {cache.name}", flush=True)
        return
    _score_and_save(name, probs, y, labels, n, time.time() - t0, summary)


def _score_and_save(name, probs, y, labels, n, seconds, summary):
    """Drop unscored (all-NaN) volumes, AUC over the 16 covered pathologies, persist."""
    item_idx = {it: labels.index(it[1]) for it in TEST_ITEMS}
    covered = sorted(set(item_idx.values()))
    keep = ~np.isnan(probs[:, covered]).any(1)            # volumes that scored >=1 organ
    sub_labels = [labels[c] for c in covered]
    row = C.save_run(MODEL, CONFIG, name, "native", probs[keep][:, covered], y[:n][keep][:, covered],
                     sub_labels, int(keep.sum()), RESULTS, seconds,
                     extra={"input_source": "native", "covered_pathologies": len(covered),
                            "note": "organ-ROI; 16/18 pathologies (no Medical material/Lymphadenopathy)"})
    summary.append(row)


def finalize_dataset(name, nshards, summary):
    """Concatenate the per-shard probs blocks (in load order) and score — no GPU/model."""
    df, _h5, y, labels, _p = C.load_dataset(name)
    n = len(df)
    blocks = []
    for s in range(nshards):
        cache = RESULTS / f"{name}__shard{s}of{nshards}__probsblock.npy"
        if not cache.exists():
            raise FileNotFoundError(f"finalize {name}: missing shard cache {cache}")
        blocks.append(np.load(cache))
    probs = np.concatenate(blocks, axis=0)
    if len(probs) != n:
        raise ValueError(f"finalize {name}: probs {len(probs)} != n {n}")
    _score_and_save(name, probs, y, labels, n, 0.0, summary)
    for s in range(nshards):                              # drop intermediate blocks
        (RESULTS / f"{name}__shard{s}of{nshards}__probsblock.npy").unlink(missing_ok=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--datasets", nargs="*", default=["ctrate_test"],
                    choices=["ctrate_test", "radchest", "pmbb_chest_nc"])
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--nshards", type=int, default=1, help="split each dataset into N contiguous blocks")
    ap.add_argument("--shard", type=int, default=-1,
                    help=">=0 encodes only the i-th block to a probs cache (no scoring)")
    ap.add_argument("--finalize", action="store_true",
                    help="concat the N shard probs caches + score (no GPU/model build)")
    args = ap.parse_args()
    summary = []
    if args.finalize:
        print(f"[finalize] datasets={args.datasets} nshards={args.nshards}")
        for ds in args.datasets:
            finalize_dataset(ds, args.nshards, summary)
        C.write_summary(summary, RESULTS, "f-VLM — exp1 zero-shot (native, organ-ROI)")
        return
    assert WEIGHTS.exists(), f"missing f-VLM weights at {WEIGHTS}"
    print(f"Model: {MODEL} / {CONFIG}  |  datasets={args.datasets}  shard={args.shard}/{args.nshards}")
    model = build_fvlm()
    for ds in args.datasets:
        run_dataset(model, ds, args.limit, summary, args.nshards, args.shard)
    if args.shard < 0:
        C.write_summary(summary, RESULTS, "f-VLM — exp1 zero-shot (native, organ-ROI)")


if __name__ == "__main__":
    main()
